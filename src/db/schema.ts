// Connected support mailboxes polled by src/cron/inboundEmail.cron.ts —
// imapPasswordEncrypted is AES-256-GCM ciphertext (see src/lib/encryption.ts),
// never returned to the client once saved. lastUid is the IMAP UID watermark
// so each poll only fetches messages newer than the last one processed.
export const supportInbox = mysqlTable("support_inboxes", {
  id: varchar("id", { length: 36 }).default(sql`(uuid())`).primaryKey(),
  name: varchar("name", { length: 255 }).notNull().unique(),
  imapHost: text("imap_host").notNull(),
  imapPort: int("imap_port").notNull().default(993),
  imapSecure: boolean("imap_secure").notNull().default(true),
  imapUser: text("imap_user").notNull(),
  // Exactly one of imapPasswordEncrypted (authType 'password') or the three
  // ms* fields (authType 'microsoft_oauth') is populated — enforced in
  // supportInbox.schema.ts, not at the DB level.
  authType: text("auth_type").notNull().default("password"),
  imapPasswordEncrypted: text("imap_password_encrypted"),
  // Outbound (ticket replies) — reuses imapUser/imapPasswordEncrypted for
  // auth, only wired up for authType 'password' inboxes.
  smtpHost: text("smtp_host"),
  smtpPort: int("smtp_port"),
  msTenantId: text("ms_tenant_id"),
  msClientId: text("ms_client_id"),
  msClientSecretEncrypted: text("ms_client_secret_encrypted"),
  folder: text("folder").notNull().default("INBOX"),
  pipelineId: varchar("pipeline_id", { length: 36 }).notNull().references(() => pipeline.id, { onDelete: "restrict" }),
  defaultStageId: varchar("default_stage_id", { length: 36 }).notNull().references(() => pipelineStage.id, { onDelete: "restrict" }),
  lastUid: int("last_uid").notNull().default(0),
  enabled: boolean("enabled").notNull().default(false),
  createdAt: datetime("created_at").default(sql`(CURRENT_TIMESTAMP)`).notNull(),
  updatedAt: datetime("updated_at").default(sql`(CURRENT_TIMESTAMP)`).notNull(),
});

// Thread ledger for inbound email processing: one row per email seen, keyed
// by its Message-ID header. Lets a later reply (matched via its
// In-Reply-To/References headers) resolve back to the ticket it belongs to
// instead of creating a duplicate. ticketId intentionally has no FK — tickets
// live in the `dynamic` Postgres schema, so this mirrors how dynamicAssociation
// already links across schemas via plain columns rather than a constraint.
export const processedInboundEmail = mysqlTable("processed_inbound_emails", {
  id: varchar("id", { length: 36 }).default(sql`(uuid())`).primaryKey(),
  supportInboxId: varchar("support_inbox_id", { length: 36 }).notNull().references(() => supportInbox.id, { onDelete: "cascade" }),
  // 255 rather than the RFC 5322 max (998) — needs to stay short enough that
  // the composite unique index below (with support_inbox_id) fits under
  // MySQL's 3072-byte max key length; real Message-IDs are far shorter.
  messageId: varchar("message_id", { length: 255 }).notNull(),
  ticketId: varchar("ticket_id", { length: 36 }).notNull(),
  processedAt: datetime("processed_at").default(sql`(CURRENT_TIMESTAMP)`).notNull(),
}, (table) => ({
  inboxMessageUnique: uniqueIndex("processed_inbound_emails_support_inbox_id_message_id_unique").on(table.supportInboxId, table.messageId),
  ticketIdx: index("processed_inbound_emails_ticket_id_idx").on(table.ticketId),
}));

// Knowledge base: categories are the top-level squares shown on the KB home
// page. Categories have no visibility tier of their own - a category can mix
// articles of any tier, so its effective visibility is derived at query time
// from whichever articles it contains (see kb.repository.ts findPublicCategories).
// Visibility (public < customer < partner < internal) lives on kb_articles only.
export const kbCategory = mysqlTable("kb_categories", {
  id: varchar("id", { length: 36 }).default(sql`(uuid())`).primaryKey(),
  slug: varchar("slug", { length: 255 }).notNull().unique(),
  title: text("title").notNull(),
  // Per-language display name overrides, e.g. { pt: "Configurações", es:
  // "Configuración" } - `title` above is always the English/default name and
  // the fallback when a language has no translation set.
  translations: json("translations").$type<Record<string, string>>(),
  description: text("description"),
  imageUrl: text("image_url"),
  sortOrder: int("sort_order").notNull().default(0),
  createdAt: datetime("created_at").default(sql`(CURRENT_TIMESTAMP)`).notNull(),
  updatedAt: datetime("updated_at").default(sql`(CURRENT_TIMESTAMP)`).notNull(),
});

export const kbSubcategory = mysqlTable("kb_subcategories", {
  id: varchar("id", { length: 36 }).default(sql`(uuid())`).primaryKey(),
  categoryId: varchar("category_id", { length: 36 }).notNull().references(() => kbCategory.id, { onDelete: "cascade" }),
  slug: text("slug").notNull(),
  title: text("title").notNull(),
  // Per-language display name overrides, same convention as kbCategory.translations.
  translations: json("translations").$type<Record<string, string>>(),
  sortOrder: int("sort_order").notNull().default(0),
  createdAt: datetime("created_at").default(sql`(CURRENT_TIMESTAMP)`).notNull(),
  updatedAt: datetime("updated_at").default(sql`(CURRENT_TIMESTAMP)`).notNull(),
}, (table) => ({
  categoryIdx: index("kb_subcategories_category_id_idx").on(table.categoryId),
}));

// content is the WYSIWYG editor's innerHTML. An article's category/
// subcategory/slug are its own and independent per language - translationGroupId
// is what actually links language variants of the same logical article
// together (see kb.service.ts groupArticleWith): a shared, otherwise-meaningless
// uuid, null for articles that aren't grouped with anything. Kept as a plain
// column (not a FK) since it's symmetric - every article in a group points at
// the same value, none of them is "the" owner.
export const kbArticle = mysqlTable("kb_articles", {
  id: varchar("id", { length: 36 }).default(sql`(uuid())`).primaryKey(),
  categoryId: varchar("category_id", { length: 36 }).notNull().references(() => kbCategory.id, { onDelete: "cascade" }),
  subcategoryId: varchar("subcategory_id", { length: 36 }).notNull().references(() => kbSubcategory.id, { onDelete: "cascade" }),
  slug: varchar("slug", { length: 255 }).notNull(),
  language: varchar("language", { length: 5 }).notNull().default("en"),
  title: text("title").notNull(),
  subtitle: text("subtitle"),
  content: text("content").notNull().default(""),
  visibility: varchar("visibility", { length: 20 }).notNull().default("internal"),
  status: varchar("status", { length: 20 }).notNull().default("draft"),
  translationGroupId: varchar("translation_group_id", { length: 36 }),
  createdAt: datetime("created_at").default(sql`(CURRENT_TIMESTAMP)`).notNull(),
  updatedAt: datetime("updated_at").default(sql`(CURRENT_TIMESTAMP)`).notNull(),
}, (table) => ({
  categoryIdx: index("kb_articles_category_id_idx").on(table.categoryId),
  subcategoryIdx: index("kb_articles_subcategory_id_idx").on(table.subcategoryId),
  translationGroupIdx: index("kb_articles_translation_group_id_idx").on(table.translationGroupId),
  subcatSlugLangUnique: uniqueIndex("kb_articles_subcat_slug_lang_unique").on(table.subcategoryId, table.slug, table.language),
}));

