export const users = mysqlTable("users", {
  id: varchar("id", { length: 36 }).default(sql`(uuid())`).primaryKey(),
  firstName: varchar("first_name", { length: 100 }).notNull(),
  lastName: varchar("last_name", { length: 100 }).notNull(),
  email: varchar("email", { length: 255 }).notNull().unique(),
  passwordHash: varchar("password_hash", { length: 255 }).notNull(),
  // Only meaningful for accountType partner/customer (e.g. 'partner_admin',
  // 'customer_user') — internal users are governed by permissionSetId instead.
  role: varchar("role", { length: 50 }).notNull().default('admin'),
  accountType: varchar("account_type", { length: 20 }).notNull().default('internal'),
  // Which dynamic.companies row this partner/customer user belongs to. No FK:
  // dynamic.* gets wiped/resynced from HubSpot, same reasoning as
  // dynamicAssociation/recordHistory avoiding cross-schema FKs.
  companyId: varchar("company_id", { length: 36 }),
  // Manual mapping to a HubSpot owner (dynamic.*.hubspot_owner_id) so internal
  // "own record" scoping can match a login to its book of business — there's
  // no HubSpot-owners sync in this app, so an admin sets this by hand today.
  hubspotOwnerId: text("hubspot_owner_id"),
  permissionSetId: varchar("permission_set_id", { length: 36 }).references(() => permissionSet.id, { onDelete: "set null" }),
  // Job title (e.g. "Territory Manager") — distinct from `role`, which is a
  // system/portal permission role, not a job title. Surfaced read-only as the
  // quote sender's title in the quote wizard.
  jobTitle: text("job_title"),
  phone: text("phone"),
  // Which object list to land on after login (Settings > Your Preferences >
  // General > Profile) — one of src/lib/permissions.ts's LANDING_PAGE_OPTIONS.
  defaultLandingPage: text("default_landing_page").notNull().default('dashboard'),
  // GCS private-bucket object key (e.g. "users/<id>") for the profile photo
  // uploaded via Settings > Your Preferences > General > Profile — streamed
  // back through GET /api/auth/me/avatar, never a raw GCS URL (see
  // src/lib/storage.ts). Null until the user uploads a photo.
  avatarKey: text("avatar_key"),
  // Null means the user is still on the random placeholder hash issued at
  // invite time and hasn't completed setup yet — see the user-invite flow in
  // src/modules/users/user.service.ts. Stamped by auth.repository.ts's
  // updatePassword (reset/self-service change) or user.repository.ts's
  // update() (admin directly sets a password).
  passwordSetAt: datetime("password_set_at"),
  createdAt: datetime("created_at").default(sql`(CURRENT_TIMESTAMP)`).notNull(),
  updatedAt: datetime("updated_at").default(sql`(CURRENT_TIMESTAMP)`).notNull(),
});

// Internal-only: named, admin-configurable permission sets (e.g.
// "Administrator", "Sales Rep"). Assigned to users via users.permissionSetId.
export const permissionSet = mysqlTable("permission_sets", {
  id: varchar("id", { length: 36 }).default(sql`(uuid())`).primaryKey(),
  name: varchar("name", { length: 255 }).notNull().unique(),
  createdAt: datetime("created_at").default(sql`(CURRENT_TIMESTAMP)`).notNull(),
  updatedAt: datetime("updated_at").default(sql`(CURRENT_TIMESTAMP)`).notNull(),
});

// One row per (permission set, module) — the per-action grants an admin
// toggles in the Permission Sets settings page. mergeScope is stored but not
// enforced anywhere yet; there's no merge feature to gate.
export const permissionSetModule = mysqlTable("permission_set_modules", {
  id: varchar("id", { length: 36 }).default(sql`(uuid())`).primaryKey(),
  permissionSetId: varchar("permission_set_id", { length: 36 }).notNull().references(() => permissionSet.id, { onDelete: "cascade" }),
  module: varchar("module", { length: 30 }).notNull(),
  viewScope: varchar("view_scope", { length: 10 }).notNull().default("none"),
  canCreate: boolean("can_create").notNull().default(false),
  editScope: varchar("edit_scope", { length: 10 }).notNull().default("none"),
  deleteScope: varchar("delete_scope", { length: 10 }).notNull().default("none"),
  mergeScope: varchar("merge_scope", { length: 10 }).notNull().default("none"),
  createdAt: datetime("created_at").default(sql`(CURRENT_TIMESTAMP)`).notNull(),
  updatedAt: datetime("updated_at").default(sql`(CURRENT_TIMESTAMP)`).notNull(),
}, (table) => ({
  permSetModuleUnique: uniqueIndex("permission_set_modules_permission_set_id_module_unique").on(table.permissionSetId, table.module),
}));

